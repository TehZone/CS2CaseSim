const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('native', {
  build: ipcRenderer.sendSync('app:build'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateDownload: () => ipcRenderer.invoke('update:download'),
  updateCancel: () => ipcRenderer.invoke('update:cancel'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  updatePage: () => ipcRenderer.invoke('update:page'),
  onUpdateProgress: (cb) => ipcRenderer.on('update:progress', (_e, p) => cb(p)),
  loadSave: () => ipcRenderer.invoke('save:load'),
  writeSave: (text) => ipcRenderer.invoke('save:write', text),
  writeSaveSync: (text) => ipcRenderer.sendSync('save:writeSync', text),
  deleteSave: () => ipcRenderer.invoke('save:delete'),
  refreshPrices: () => ipcRenderer.invoke('prices:refresh'),
  resetPrices: () => ipcRenderer.invoke('prices:reset'),
  onPriceProgress: (cb) => ipcRenderer.on('prices:progress', (_e, msg) => cb(msg)),
  openExternal: (url) => ipcRenderer.invoke('app:openExternal', url),
  clearImageCache: () => ipcRenderer.invoke('app:clearImageCache'),
  info: () => ipcRenderer.invoke('app:info'),
  display: () => ipcRenderer.invoke('app:display'),
  setDisplay: (d) => ipcRenderer.invoke('app:setDisplay', d),
  relaunch: () => ipcRenderer.invoke('app:relaunch'),
  saveLog: (name, text) => ipcRenderer.invoke('app:saveLog', name, text),
  showLog: (file) => ipcRenderer.invoke('app:showLog', file),
  cs2Status: () => ipcRenderer.invoke('cs2:status'),
  cs2Prepare: (req) => ipcRenderer.invoke('cs2:prepare', req),
  cs2Clear: () => ipcRenderer.invoke('cs2:clear'),
  cs2PrepareAll: (content) => ipcRenderer.invoke('cs2:prepareAll', content),
  cs2PrepareStatus: () => ipcRenderer.invoke('cs2:prepareStatus'),
  cs2PrepareCancel: () => ipcRenderer.invoke('cs2:prepareCancel'),
  cs2CacheSize: () => ipcRenderer.invoke('cs2:cacheSize'),
  cs2Sounds: () => ipcRenderer.invoke('cs2:sounds'),
  cs2Sticker: (material) => ipcRenderer.invoke('cs2:sticker', material),
  cs2VanityMaps: () => ipcRenderer.invoke('cs2:vanityMaps'),
  cs2Vanity: (id) => ipcRenderer.invoke('cs2:vanity', id),
  cs2GloveClip: () => ipcRenderer.invoke('cs2:gloveClip'),
  cs2FirstPerson: (weapon) => ipcRenderer.invoke('cs2:firstPerson', weapon),
  cs2StatTrak: (weapon) => ipcRenderer.invoke('cs2:statTrak', weapon),
  cs2Charm: (mdl, mat) => ipcRenderer.invoke('cs2:charm', mdl, mat),
  cs2CharmAttach: (weapon) => ipcRenderer.invoke('cs2:charmAttach', weapon),
  cs2WeaponMarkup: (weapon) => ipcRenderer.invoke('cs2:weaponMarkup', weapon),
  cs2Crate: (id) => ipcRenderer.invoke('cs2:crate', id),
  cs2Play: (fn, arg) => ipcRenderer.invoke('cs2:play', fn, arg),
});
